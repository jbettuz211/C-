//Criar um programa em C que exiba os números de 1 a 1000. -- Estrutura do while

#include <stdio.h>

int main(){
    //var da estrutura do while
    int contador= 0;

    //Estrutura do while
    do
    {
        printf("%d\n", contador);
        contador++;
    } while (contador != 1001);
    
    







    return 0;
}