// Criar um programa em C que exiba o valor do contador que irá variar seu valor de 1 a 25 -- Usando do while

#include <stdio.h>

int main(){
    //var da estrutura do while
    int contador= 0;

    //Estrutura do while
    do
    {
        printf("%d\n", contador);
        contador++;
    } while (contador != 26);
    
    







    return 0;
}